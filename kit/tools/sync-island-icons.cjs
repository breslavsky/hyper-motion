const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');

// Bundle only the selected upstream SVGs. Their original geometry, attributes
// and license comments remain intact; the component only sizes the SVG box.
function syncIslandIcons(directory=path.resolve(__dirname,'../source/lib/components/upstream/lucide-static')){
  const receipt=JSON.parse(fs.readFileSync(path.join(directory,'RECEIPT.json'),'utf8'));
  for(const [file,expected] of Object.entries(receipt.sha256)){
    const actual=crypto.createHash('sha256').update(fs.readFileSync(path.join(directory,file))).digest('hex');
    if(actual!==expected)throw new Error(`Lucide upstream asset differs from receipt: ${file}`);
  }
  const icons=Object.fromEntries(Object.entries(receipt.icons).map(([name,file])=>[name,fs.readFileSync(path.join(directory,file),'utf8')]));
  const source=`// Generated by tools/sync-island-icons.cjs from lucide-static ${receipt.version}.\n// See LICENSE and RECEIPT.json beside this file for upstream license/provenance.\nexport const islandIcons=Object.freeze(${JSON.stringify(icons,null,2)});\n`;
  const target=path.join(directory,'icons.mjs');
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==source)fs.writeFileSync(target,source);
  return target;
}
module.exports={syncIslandIcons};
if(require.main===module)console.log(syncIslandIcons(process.argv[2]));
