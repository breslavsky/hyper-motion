const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');

// Bundle the selected marks of Simple Icons as they came: one path each on a
// 24-unit square, with the colour its owner uses. RECEIPT.json pins the npm
// release and every file.
function syncSocialIcons(directory=path.resolve(__dirname,'../source/lib/components/upstream/simple-icons')){
  const receipt=JSON.parse(fs.readFileSync(path.join(directory,'RECEIPT.json'),'utf8'));
  for(const [file,expected] of Object.entries(receipt.sha256)){
    const actual=crypto.createHash('sha256').update(fs.readFileSync(path.join(directory,file))).digest('hex');
    if(actual!==expected)throw new Error(`Simple Icons upstream asset differs from receipt: ${file}`);
  }
  const icons=Object.fromEntries(Object.entries(receipt.icons).map(([name,{title,file,hex}])=>[name,{title,hex,svg:fs.readFileSync(path.join(directory,file),'utf8')}]));
  const source=`// Generated by tools/sync-social-icons.cjs from simple-icons ${receipt.version}.\n// See LICENSE.md, DISCLAIMER.md and RECEIPT.json beside this file: the collection is CC0,\n// every mark is its owner's trademark.\nexport const socialIcons=Object.freeze(${JSON.stringify(icons,null,2)});\n`;
  const target=path.join(directory,'icons.mjs');
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==source)fs.writeFileSync(target,source);
  return target;
}
module.exports={syncSocialIcons};
if(require.main===module)console.log(syncSocialIcons(process.argv[2]));
